// +2 to the chosen archetype, +1 to its neighbour; direction flips on the motivation question.
const SECONDARY = [(i: number) => (i + 1) % 3, (i: number) => (i + 2) % 3, (i: number) => (i + 1) % 3];
export const MAX_SCORE = 6;

export const resolve = (clusterId: ClusterId, answers: number[]) => {
  const keys = CLUSTERS.find((c) => c.id === clusterId)!.keys;
  const s = Object.fromEntries(keys.map((k) => [k, 0])) as Record<ArchKey, number>;
  answers.forEach((choice, qi) => {
    s[keys[choice]] += 2;
    s[keys[SECONDARY[qi](choice)]] += 1;
  });
  const max = Math.max(...keys.map((k) => s[k]));
  const top = keys.filter((k) => s[k] === max);
  const winner = top.length === 1 ? top[0] : top.includes(keys[answers[1]]) ? keys[answers[1]] : top[0];
  const runnerUp = keys.filter((k) => k !== winner).sort((a, b) => s[b] - s[a])[0];
  return { scores: s, winner, runnerUp };
};

